import { readFile, writeFile, readdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import { resolve, join } from "node:path";
import { fileURLToPath } from "node:url";
import { isDeepStrictEqual } from "node:util";
import { format } from "prettier";

/**
 * @param {string | Buffer} raw - Exact UTF-8 source or binary asset bytes.
 * @returns {string} Lowercase SHA-256 content identity.
 */
const digest = (raw) => createHash("sha256").update(raw).digest("hex");

/**
 * @param {string} directory - Actual atlas source directory.
 * @returns {Promise<string[]>} Regular assets; symbolic links are refused.
 */
async function members(directory) {
  const found = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.isSymbolicLink())
      throw new Error("Atlas assets must be regular files.");
    if (entry.isDirectory()) {
      for (const name of await members(join(directory, entry.name)))
        found.push(entry.name + "/" + name);
    } else found.push(entry.name);
  }
  return found.sort();
}

/**
 * Check or regenerate content-bound module URLs, the manifest and its size table.
 * Canonical data JSON is never rewritten. Equal embedded payloads retain their bytes;
 * a changed canonical payload is re-embedded only in explicit write mode.
 * @param {string} directory - Complete local atlas tree.
 * @param {{write?: boolean}} [options] - Write derived files rather than checking drift.
 * @returns {Promise<{assets: number, bytes: number}>} Verified managed inventory size.
 * @throws {Error} Missing inputs, unlisted assets, malformed data or derived-file drift.
 */
export async function renderAtlas(directory, { write = false } = {}) {
  /** @type {Omit<typeof import('../docs/atlas/atlas-manifest.json'), 'files'> & {files: Record<string, string>}} */
  const manifest = JSON.parse(
    await readFile(join(directory, "atlas-manifest.json"), "utf8"),
  );
  /** @type {Record<string, string>} */
  const original = manifest.files;
  const names = await members(directory);
  const allowed = new Set([
    ...Object.keys(original),
    "legacy-atlas.js",
    "legacy-budget.js",
    "atlas-manifest.json",
    "README.md",
    "LICENSE",
  ]);
  if (
    names.some((name) => !allowed.has(name)) ||
    Object.keys(original).some((name) => !names.includes(name))
  ) {
    throw new Error("Atlas has missing or unlisted assets.");
  }
  /** @type {Map<string, Buffer>} */
  const files = new Map();
  for (const name of names)
    files.set(name, await readFile(join(directory, name)));
  /**
   * Resolve an expected input before deriving any output; absence fails closed.
   * @param {string} name - Manifest member or required data/entry file.
   * @returns {Buffer} Original or currently regenerated bytes.
   */
  function asset(name) {
    const raw = files.get(name);
    if (raw === undefined)
      throw new Error("Required atlas asset is missing: " + name);
    return raw;
  }
  /** @type {{public_sources:string[],public_guides:string[],withheld_nodes:Record<string,import('../types/atlas.js').AtlasNode>,withheld_assets:string[],approved_static_assets:Record<string,string[]>}} */
  const policy = JSON.parse(
    await readFile(
      new URL("./atlas_publication_policy.json", import.meta.url),
      "utf8",
    ),
  );
  const publicSources = new Set(policy.public_sources);
  const publicGuides = new Set(policy.public_guides);
  if (names.some((name) => policy.withheld_assets.includes(name)))
    throw new Error("Repository-internal contents are not publishable.");
  for (const name of names.filter((name) => /\.(?:svg|png|pdf)$/.test(name)))
    if (
      !Object.hasOwn(policy.approved_static_assets, name) ||
      !policy.approved_static_assets[name].includes(digest(asset(name)))
    )
      throw new Error("Repository-internal contents are not publishable.");
  /** @type {import('../types/atlas.js').DocumentData} */
  const library = JSON.parse(
    asset("document_library_candidate.json").toString("utf8"),
  );
  /** @type {import('../types/atlas.js').TechnicalData} */
  const technical = JSON.parse(
    asset("technical_explanations_candidate.json").toString("utf8"),
  );
  for (const source of [library, technical.library])
    for (const project of source.projects)
      if (!publicSources.has(project.project_id) && project.documents.length)
        throw new Error("Repository-internal contents are not publishable.");
  /** @type {import('../types/atlas.js').DirectData} */
  const direct = JSON.parse(
    asset("direct_repository_sources.json").toString("utf8"),
  );
  for (const project of direct.projects)
    if (
      !publicSources.has(project.project_id) &&
      (project.documents.length ||
        Object.keys(project.declared_package_metadata).length ||
        Object.keys(project.boundary_declarations).length ||
        project.readme_excerpts.length ||
        project.architecture_documents.length)
    )
      throw new Error("Repository-internal contents are not publishable.");
  if (
    technical.references.some((row) => !publicSources.has(row.project)) ||
    technical.guides.some((row) => !publicGuides.has(row.project_id)) ||
    Object.keys(technical.guide_source_captures).some((id) =>
      Object.hasOwn(policy.withheld_nodes, id),
    )
  )
    throw new Error("Repository-internal contents are not publishable.");
  /** @type {import('../types/atlas.js').VisualData} */
  const visuals = JSON.parse(asset("visual_catalogue.json").toString("utf8"));
  /** @type {import('../types/atlas.js').UpdateData} */
  const updates = JSON.parse(
    asset("source_update_candidate.json").toString("utf8"),
  );
  if (
    visuals.illustrations.some((row) =>
      Object.hasOwn(policy.withheld_nodes, row.project),
    ) ||
    updates.projects.some((row) =>
      Object.hasOwn(policy.withheld_nodes, row.project_id),
    )
  )
    throw new Error("Repository-internal contents are not publishable.");
  /** @type {import('../types/atlas.js').AtlasData} */
  const atlas = JSON.parse(asset("public_atlas_data.json").toString("utf8"));
  for (const node of atlas.nodes)
    if (
      Object.hasOwn(policy.withheld_nodes, node.id) &&
      !isDeepStrictEqual(node, policy.withheld_nodes[node.id])
    )
      throw new Error("Repository-internal contents are not publishable.");
  for (const edge of atlas.edges)
    if (
      (Object.hasOwn(policy.withheld_nodes, edge.from) ||
        Object.hasOwn(policy.withheld_nodes, edge.to)) &&
      !isDeepStrictEqual(edge, {
        from: edge.from,
        to: edge.to,
        kind: edge.kind,
        evidence:
          "Architecture relationship; repository contents are not published.",
      })
    )
      throw new Error("Repository-internal contents are not publishable.");
  const staticMap = asset("atlas_full.html").toString("utf8");
  for (const card of staticMap.matchAll(
    /<g\b(?=[^>]*\bclass="node")(?=[^>]*\bdata-id="([^"]+)")[^>]*>[\s\S]*?<\/g>/g,
  )) {
    const node = policy.withheld_nodes[card[1]];
    if (node) {
      const expected = (
        node.name +
        ": " +
        node.function +
        "\n" +
        node.phase +
        "\nLicence: " +
        node.licence
      )
        .replaceAll("&", "&amp;")
        .replaceAll("<", "&lt;")
        .replaceAll(">", "&gt;")
        .replaceAll('"', "&quot;")
        .replaceAll("'", "&#x27;")
        .replace(/\s+/g, " ")
        .trim();
      const title = card[0].match(/<title[^>]*>([\s\S]*?)<\/title>/);
      if (!title || title[1].replace(/\s+/g, " ").trim() !== expected)
        throw new Error("Repository-internal contents are not publishable.");
      const expectedLabel = (
        node.name +
        " " +
        node.work_status +
        " · " +
        (node.repository_record
          ? "architecture stage: a reviewed boundary and validation tooling, no model"
          : "Contents are not published.") +
        " Licence: " +
        node.licence
      )
        .replaceAll("&", "&amp;")
        .replaceAll("<", "&lt;")
        .replaceAll(">", "&gt;")
        .replaceAll('"', "&quot;")
        .replaceAll("'", "&#x27;");
      const label = card[0].match(/\baria-label="([^"]*)"/);
      if (!label || label[1] !== expectedLabel)
        throw new Error(
          "Accessible label does not match the approved publication label.",
        );
      const descriptionId = "atlas-purpose-" + digest(node.id).slice(0, 16);
      const description = card[0].match(/\baria-describedby="([^"]*)"/);
      if (
        !description ||
        description[1] !== descriptionId ||
        !title[0].includes('id="' + descriptionId + '"')
      )
        throw new Error(
          "Accessible description does not match the approved project purpose.",
        );
    }
  }
  const javascript = names.filter((name) => name.endsWith(".js"));
  const imports = Object.fromEntries(
    javascript.map((name) => [
      "@atlas/" + name.slice(0, -3),
      "./" + name + "?v=" + digest(asset(name)),
    ]),
  );
  /** @type {Record<string, string>} */
  const payloads = {
    "atlas-data": "public_atlas_data.json",
    "resource-data": "public_resources_data.json",
    "budget-data": "public_budget_data.json",
    "source-update-data": "source_update_candidate.json",
    "visual-data": "visual_catalogue.json",
    "direct-source-data": "direct_repository_sources.json",
    "document-library-data": "document_library_candidate.json",
    "technical-data": "technical_explanations_candidate.json",
  };
  /** @type {Record<string, string[]>} Required embedded source payloads per maintained entry. */
  const entries = {
    "index.html": Object.keys(payloads),
    "resources.html": ["resource-data"],
    "atlas_full.html": ["atlas-data"],
    "budget.html": ["budget-data"],
  };
  for (const [name, required] of Object.entries(entries)) {
    let html = asset(name).toString("utf8");
    for (const [id, source] of Object.entries(payloads)) {
      const pattern = new RegExp(
        '(<script id="' +
          id +
          '" type="application/json">)([\\s\\S]*?)(</script>)',
        "g",
      );
      const data = JSON.parse(asset(source).toString("utf8"));
      if (required.includes(id) && [...html.matchAll(pattern)].length !== 1)
        throw new Error(
          "Entry must contain exactly one required payload: " + name + "/" + id,
        );
      html = html.replace(pattern, (whole, open, body, close) =>
        isDeepStrictEqual(JSON.parse(body), data)
          ? whole
          : open + JSON.stringify(data).replaceAll("<", "\\u003c") + close,
      );
    }
    html = html.replace(
      /<script type="importmap">[\s\S]*?<\/script>/,
      '<script type="importmap">' + JSON.stringify({ imports }) + "</script>",
    );
    html = html.replace(
      /(<script\s+type="module"\s+src=")([^"?]+)(?:\?v=[a-f0-9]+)?("\s*><\/script>)/g,
      (_whole, open, script, close) =>
        open + script + "?v=" + digest(asset(script)) + close,
    );
    html = html.replace(
      /(?:<!-- prettier-ignore -->\s*)?(<script id="[^"]+" type="application\/json">)/g,
      "<!-- prettier-ignore -->\n$1",
    );
    files.set(name, Buffer.from(await format(html, { parser: "html" })));
  }
  const assetNames = names.filter(
    (name) => !["atlas-manifest.json", "README.md", "LICENSE"].includes(name),
  );
  const bytes = assetNames.reduce(
    (total, name) => total + asset(name).length,
    0,
  );
  manifest.files = Object.fromEntries(
    assetNames.map((name) => [name, digest(asset(name))]),
  );
  files.set(
    "atlas-manifest.json",
    Buffer.from(JSON.stringify(manifest, null, 2) + "\n"),
  );
  const readme = asset("README.md")
    .toString("utf8")
    .replace(
      /(\| Interactive site snapshot\s*\|\s*)\d+ manifest-listed assets(\s*\|\s*)[\d,]+(\s*\|)/,
      (_whole, prefix, separator, suffix) =>
        prefix +
        assetNames.length +
        " manifest-listed assets" +
        separator +
        bytes.toLocaleString("en-GB") +
        suffix,
    )
    .replace(
      /(\| Main interactive entry page\s*\|[^|\n]+\|\s*)[\d,]+(\s*\|)/,
      (_whole, prefix, suffix) =>
        prefix + asset("index.html").length.toLocaleString("en-GB") + suffix,
    );
  files.set(
    "README.md",
    Buffer.from(await format(readme, { parser: "markdown" })),
  );
  for (const [name, raw] of files) {
    const previous = await readFile(join(directory, name));
    if (previous.equals(raw)) continue;
    if (!write) throw new Error("Derived atlas file differs: " + name);
    await writeFile(join(directory, name), raw);
  }
  return { assets: assetNames.length, bytes };
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const args = process.argv.slice(2);
  const directory = args[1]
    ? resolve(args[1])
    : fileURLToPath(new URL("../docs/atlas", import.meta.url));
  if (
    (args.length !== 1 && args.length !== 2) ||
    !["--check", "--write"].includes(args[0])
  ) {
    console.error(
      "Usage: node tools/render_atlas.mjs --check|--write [atlas-directory]",
    );
    process.exitCode = 2;
  } else {
    try {
      console.log(
        JSON.stringify(
          await renderAtlas(directory, { write: args[0] === "--write" }),
        ),
      );
    } catch (error) {
      console.error(String(error));
      process.exitCode = 1;
    }
  }
}
