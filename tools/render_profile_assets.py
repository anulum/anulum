@dataclass(frozen=True)
class Counts:
    """Repository counts derived from the manifest."""

    portfolios: int
    repositories: int
    public: int
    private: int
    standalone: int
    verified_at: str
    per_portfolio: dict[str, tuple[int, int]]

    def desc(self) -> str:
        """Return the machine-readable count line embedded in every SVG."""
        groups = " ".join(f"{key}={public}/{private}" for key, (public, private) in self.per_portfolio.items())
        return (
            f"counts: portfolios={self.portfolios} repositories={self.repositories} "
            f"public={self.public} private={self.private} standalone={self.standalone} "
            f"verified={self.verified_at}; {groups}"
        )


def load_counts(data: dict[str, Any]) -> Counts:
    """Derive every rendered number from the manifest."""
    per: dict[str, tuple[int, int]] = {}
    for portfolio in data["portfolios"]:
        repos = portfolio["repositories"]
        public = sum(1 for repo in repos if repo["access"] == "public")
        private = sum(1 for repo in repos if repo["access"] == "private")
        per[portfolio["id"]] = (public, private)
    return Counts(
        portfolios=len(data["portfolios"]),
        repositories=sum(p + q for p, q in per.values()),
        public=sum(p for p, _ in per.values()),
        private=sum(q for _, q in per.values()),
        standalone=len(data["standalone_repositories"]),
        verified_at=data["verified_at"],
        per_portfolio=per,
    )


class Typesetter:
    """Convert text runs into SVG path groups using the bundled variable font."""

    def __init__(self, font_files: tuple[Path, ...]) -> None:
        self._files = font_files
        self._instances: dict[tuple[Path, int], tuple[Any, dict[int, str], int]] = {}
        self._defs: dict[str, str] = {}

    def reset(self) -> None:
        """Forget the glyph definitions collected for the previous document."""
        self._defs = {}

    def defs(self) -> str:
        """Return one ``<path>`` definition per glyph used since :meth:`reset`."""
        return "".join(f'<path id="{key}" d="{d}"/>' for key, d in sorted(self._defs.items()))

    def _instance(self, path: Path, weight: int) -> tuple[Any, dict[int, str], int]:
        key = (path, weight)
        if key not in self._instances:
            font = TTFont(str(path))
            static = instancer.instantiateVariableFont(font, {"wght": weight})
            self._instances[key] = (static.getGlyphSet(), static.getBestCmap(), static["head"].unitsPerEm)
        return self._instances[key]

    def _glyph(self, char: str, weight: int) -> tuple[Any, str, int] | None:
        for path in self._files:
            glyph_set, cmap, upm = self._instance(path, weight)
            name = cmap.get(ord(char))
            if name is not None:
                return glyph_set, name, upm
        return None

    def measure(self, text: str, size: float, weight: int, letter_spacing: float = 0.0) -> float:
        """Return the advance width of ``text`` in user units."""
        width = 0.0
        for char in text:
            found = self._glyph(char, weight)
            if found is None:
                raise ValueError(f"glyph missing in bundled fonts: {char!r}")
            glyph_set, name, upm = found
            width += glyph_set[name].width * size / upm + letter_spacing
        return width - letter_spacing if text else 0.0

    def run(
        self,
        text: str,
        x: float,
        y: float,
        *,
        size: float,
        weight: int,
        fill: str,
        letter_spacing: float = 0.0,
        anchor: str = "start",
    ) -> str:
        """Return a ``<g>`` of glyph outlines for ``text`` with its baseline at ``y``."""
        width = self.measure(text, size, weight, letter_spacing)
        if anchor == "middle":
            x -= width / 2
        elif anchor == "end":
            x -= width
        parts: list[str] = []
        advance = 0.0
        for char in text:
            found = self._glyph(char, weight)
            assert found is not None
            glyph_set, name, upm = found
            glyph = glyph_set[name]
            scale = size / upm
            key = f"g{weight}-{name}"
            if key not in self._defs:
                pen = SVGPathPen(glyph_set, ntos=lambda value: f"{value:.0f}")
                glyph.draw(pen)
                self._defs[key] = pen.getCommands()
            if self._defs[key]:
                parts.append(
                    f'<use xlink:href="#{key}" '
                    f'transform="translate({x + advance:.1f} {y:.1f}) scale({scale:.5f} {-scale:.5f})"/>'
                )
            advance += glyph.width * scale + letter_spacing
        label = text.replace("&", "&amp;").replace("<", "&lt;")
        return f'<g fill="{fill}" aria-label="{label}">{"".join(parts)}</g>'


