"""Render the profile header and ecosystem map SVGs from ``profile-data.json``.

Every count, name and tagline in the two images comes from the manifest, so the
pictures cannot drift from the README tables that the validator already gates.
Text is emitted as glyph outlines of Space Grotesk (``assets/fonts``), because
GitHub's image proxy loads no external fonts and system fallbacks differ per
platform. Each SVG carries a machine-readable ``<desc>`` line with the counts it
was rendered from; ``validate_profile.py`` compares that line with the manifest.

Usage: ``python3 tools/render_profile_assets.py [--check]``

``--check`` renders in memory and exits 1 when any file on disk differs from a
fresh render (the CI drift gate). Requires ``fonttools`` and ``brotli``
(``tools/requirements-render.txt``).
"""

